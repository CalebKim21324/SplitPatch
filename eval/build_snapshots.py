"""Build per-patch kit snapshots -> data/champions/snapshots/<slug>/<patch>.yaml.

snapshot(p) = 26.22 kit, with base stats from data/champions/base_stats.csv for patch p, and every
Riot ability change made AFTER p reverted (newest first) using holdout/riot_changes.yaml.
Lives in eval/ because only eval/ may read holdout/. The agent's read_kit only ever returns the
snapshot for the patch it is working on, so later changes never leak.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from schemas import Kit  # noqa: E402
from sim.kits import CHAMPIONS, PATCHES, slug  # noqa: E402


def minor(p: str) -> int:
    return int(p.split(".")[1])


def snapshot(champ: str, patch: str, changes: list[dict], base_rows: list[dict]) -> dict:
    kit = Kit.load(ROOT / "data" / "champions" / f"{slug(champ)}.yaml").model_dump(by_alias=True, exclude_none=True)
    row = next(r for r in base_rows if r["champion"] == champ and r["patch"] == patch)
    for k in kit["base"]:
        kit["base"][k] = float(row[k])
    later = [c for c in changes if c["champion"] == champ and minor(c["patch"]) > minor(patch)]
    for c in sorted(later, key=lambda c: minor(c["patch"]), reverse=True):
        for f in c["fields"]:
            parts = f["field"].split(".")
            if parts[0] == "abilities":
                kit["abilities"][parts[1]][parts[2]] = f["from"]
    kit["patch"] = patch
    return Kit.model_validate(kit).model_dump(by_alias=True, exclude_none=True)


def main() -> int:
    changes = yaml.safe_load((ROOT / "holdout" / "riot_changes.yaml").read_text(encoding="utf-8"))["changes"]
    base_rows = list(csv.DictReader(open(ROOT / "data" / "champions" / "base_stats.csv", encoding="utf-8")))
    for champ in CHAMPIONS:
        out = ROOT / "data" / "champions" / "snapshots" / slug(champ)
        out.mkdir(parents=True, exist_ok=True)
        for p in PATCHES:
            (out / f"{p}.yaml").write_text(
                f"# GENERATED by eval/build_snapshots.py — {champ} kit as of patch {p}. Do not edit.\n"
                + yaml.safe_dump(snapshot(champ, p, changes, base_rows), sort_keys=False), encoding="utf-8")
    print(f"wrote {len(CHAMPIONS) * len(PATCHES)} snapshots")
    return 0


if __name__ == "__main__":
    sys.exit(main())
